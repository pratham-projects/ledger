function hash(input: string): number {
  let h = 2166136261;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** The public pool, `url` resolved through the local placeholder clip pool. */
export const TEMPLATE_VIDEOS: TemplateVideo[] = TEMPLATE_VIDEO_ENTRIES.map(({ seed, aspect }) => ({
  url: placeholderVideoSrc(seed),
  aspect,
}));

/**
 * A stable, non-repeating run of `count` clips for one category — same striding technique
 * as `stockRun` in `lib/stock.ts`: hash the seed to a start index, then step by 7 (coprime
 * with the pool size) so a short run never collides with itself. Wraps once it runs out
 * rather than reusing the same handful of clips for every category.
 */
export function videoRun(seedKey: string, count: number): TemplateVideo[] {
  const start = hash(seedKey) % TEMPLATE_VIDEOS.length;
  return Array.from(
    { length: count },
    (_, i) => TEMPLATE_VIDEOS[(start + i * 7) % TEMPLATE_VIDEOS.length]
  );
}
